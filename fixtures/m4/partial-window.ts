export function syntheticCheck(
  sourceId: (typeof M4_COHORT_SOURCE_IDS)[number],
  day: number,
  materiality: "unchanged" | "material" | "security",
  humanMinutes: number,
): RehearsalCheck {
  const base = `m4_fixture_${sourceId.replaceAll(".", "_")}_${day}`;
  const snapshot = createSnapshotArtifact({
    snapshot_id: `${base}_snapshot`,
    source_id: sourceId,
    captured_at: `2026-08-${String(day).padStart(2, "0")}T00:00:00Z`,
    capture_method: "manual_capture",
    representation_kind: "test_fixture",
    representation_digest: `sha256:test-fixture:${base}`,
    completeness: "complete",
  });
  const diff = createDiffArtifact({
    diff_id: `${base}_diff`,
    source_id: sourceId,
    before_snapshot_id: null,
    after_snapshot_id: snapshot.snapshot_id,
    changed: materiality !== "unchanged",
    classification:
      materiality === "unchanged"
        ? "unchanged"
        : materiality === "security"
          ? "security_anomaly"
          : "potential_material_rule_change",
  });
  const materialityArtifact = createMaterialityArtifact({
    materiality_id: `${base}_materiality`,
    source_id: sourceId,
    diff_id: diff.diff_id,
    materiality,
    review_required: materiality !== "unchanged",
    impact_tags: materiality === "unchanged" ? [] : [materiality],
  });
  const observation = {
    ...PERMITTED_SYNTHETIC_PERMISSION.observation,
    observation_id: `${base}_observation`,
    source_id: sourceId,
  };
  return evaluateDirectCheck({
    check_id: `${base}_check`,
    source_id: sourceId,
    checked_at: snapshot.captured_at,
    planned_method: "manual_capture",
    permission: { ...PERMITTED_SYNTHETIC_PERMISSION, observation },
    snapshot,
    diff,
    materiality: materialityArtifact,
    human_minutes: humanMinutes,
    synthetic: true,
  });
}

